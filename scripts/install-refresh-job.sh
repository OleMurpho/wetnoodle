#!/usr/bin/env bash
# install-refresh-job.sh — give a Hermes profile the wetnoodle refresh watchdog.
#
# Run this after register-mcp.sh / install-memory-provider.sh. It makes the
# archive keep itself current without a systemd unit, a crontab entry, or a
# per-machine copy of the script, so the same command works on any host:
#
#   ./scripts/install-refresh-job.sh                 # profile: default
#   ./scripts/install-refresh-job.sh -p ordo -p slartibartfast
#   ./scripts/install-refresh-job.sh -p ordo --schedule "every 30m" --deliver local
#
# What it does, per profile:
#   1. reads memory.wetnoodle.db_dir (the archive the provider actually reads)
#   2. writes <profile>/scripts/rag_auto_ingest.sh, a three-line shim that pins
#      this machine's store and checkout and execs the repo's watchdog
#   3. creates the cron job, or updates it in place if a job of that name exists
#
# The watchdog itself lives in the repo, so behaviour is identical everywhere;
# only the shim differs, and the shim is generated, never hand-edited.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HERMES_BIN="${HERMES_BIN:-$(command -v hermes || true)}"
[ -z "$HERMES_BIN" ] && [ -x "$HOME/.local/bin/hermes" ] && HERMES_BIN="$HOME/.local/bin/hermes"
[ -z "$HERMES_BIN" ] && [ -x "$HOME/.hermes/bin/hermes" ] && HERMES_BIN="$HOME/.hermes/bin/hermes"
HERMES_HOME="${RAG_HERMES_HOME:-$HOME/.hermes}"

JOB_NAME="wetnoodle-refresh"
SCHEDULE="every 30m"
DELIVER=""
PROFILES=()

die() { echo "error: $*" >&2; exit 1; }

while [ "$#" -gt 0 ]; do
    case "$1" in
        -p|--profile) [ "$#" -ge 2 ] || die "$1 needs a profile name"; PROFILES+=("$2"); shift 2 ;;
        --profile=*) PROFILES+=("${1#*=}"); shift ;;
        --schedule) [ "$#" -ge 2 ] || die "--schedule needs a value"; SCHEDULE="$2"; shift 2 ;;
        --schedule=*) SCHEDULE="${1#*=}"; shift ;;
        --deliver) [ "$#" -ge 2 ] || die "--deliver needs a value"; DELIVER="$2"; shift 2 ;;
        --deliver=*) DELIVER="${1#*=}"; shift ;;
        -h|--help) sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) die "unknown argument $1" ;;
    esac
done

[ -x "$HERMES_BIN" ] || die "hermes not found (set HERMES_BIN)"
[ -f "$ROOT/scripts/cron/rag_auto_ingest.sh" ] || die "watchdog missing from $ROOT/scripts/cron"
[ -x "$ROOT/.venv/bin/python" ] || die "no interpreter at $ROOT/.venv/bin/python — run scripts/bootstrap.sh first"

if [ "${#PROFILES[@]}" -eq 0 ]; then
    PROFILES=(default)
fi

echo "wetnoodle refresh job"
echo "  hermes  : $HERMES_BIN"
echo "  checkout: $ROOT"

for p in "${PROFILES[@]}"; do
    pdir="$HERMES_HOME/profiles/$p"
    if [ "$p" = "default" ]; then pdir="$HERMES_HOME"; fi
    [ -d "$pdir" ] || { echo "  $p: no such profile — skipped"; continue; }

    db_dir="$("$HERMES_BIN" -p "$p" config get memory.wetnoodle.db_dir 2>/dev/null | tr -d '\r\n')"
    [ -z "$db_dir" ] && db_dir="$HOME/.wetnoodle"

    script_dir="$pdir/scripts"
    mkdir -p "$script_dir"
    shim="$script_dir/rag_auto_ingest.sh"
    cat >"$shim" <<SHIM
#!/usr/bin/env bash
# generated by wetnoodle scripts/install-refresh-job.sh — re-run it rather than editing this.
# The watchdog itself lives in the checkout, so its behaviour is the same on every host.
exec env RAG_DIR="$db_dir" RAG_PYTHON="$ROOT/.venv/bin/python" WETNOODLE_SRC="$ROOT" \\
    bash "$ROOT/scripts/cron/rag_auto_ingest.sh" "\$@"
SHIM
    chmod +x "$shim"

    # Idempotent: update the existing job if this profile already has one.
    # Match the existing job by name or by the script it runs. Matching only on the name
    # would leave a second job doing the same ingest every cycle on a host that named it
    # differently, and two ingests racing is exactly what the lock exists to prevent.
    job_id="$("$HERMES_BIN" -p "$p" cron list 2>/dev/null \
        | awk -v name="$JOB_NAME" -v script="$(basename "$shim")" '
              $1 ~ /^[0-9a-f]{12}$/ {id=$1}
              $1=="Name:"   && $2==name   {print id; exit}
              $1=="Script:" && $2==script {print id; exit}')"

    deliver_args=()
    [ -n "$DELIVER" ] && deliver_args=(--deliver "$DELIVER")

    if [ -n "$job_id" ]; then
        if "$HERMES_BIN" -p "$p" cron edit "$job_id" --name "$JOB_NAME" --script "$(basename "$shim")" \
              --schedule "$SCHEDULE" --no-agent "${deliver_args[@]}" >/dev/null 2>&1; then
            echo "  $p: updated job $job_id ($SCHEDULE, store=$db_dir)"
        else
            echo "  $p: job $job_id exists but could not be updated — run 'hermes -p $p cron edit $job_id' by hand"
        fi
    else
        if out="$("$HERMES_BIN" -p "$p" cron create "$SCHEDULE" \
                   "wetnoodle refresh watchdog: incremental ingest of every session corpus plus skills. Silent unless it fails." \
                   --name "$JOB_NAME" --script "$(basename "$shim")" --no-agent \
                   "${deliver_args[@]}" 2>&1)"; then
            echo "  $p: created job ($SCHEDULE, store=$db_dir)"
        else
            echo "  $p: could not create the job: $(echo "$out" | tail -1)"
        fi
    fi
done

echo
echo "Check it:   hermes -p <profile> cron list"
echo "Force one:  hermes -p <profile> cron run <job id>"
echo "It prints nothing when the refresh succeeds; that silence is the design."
