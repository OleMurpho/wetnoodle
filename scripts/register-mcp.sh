#!/usr/bin/env bash
# register-mcp.sh — attach this archive to an EXISTING Hermes install.
#
# The manual way is to paste an mcp_servers block into each config.yaml. This
# does it for every profile instead, using Hermes's own `config set` (which
# validates the write), and generates a wrapper so the interpreter path is
# resolved once rather than per profile.
#
# Why a wrapper and not `command: .venv/bin/python` + `args: [-m, wetnoodle.mcp_server]`:
# a caller that has its own PYTHONPATH set (agent runtimes do) leaks its
# site-packages into this venv, and numpy fails to import with an ABI mismatch.
# The wrapper strips PYTHON* before exec. Same reason bootstrap.sh unsets them.
#
#   ./scripts/register-mcp.sh                 # every profile found
#   ./scripts/register-mcp.sh work personal   # only the ones named
#   ./scripts/register-mcp.sh --scope-shared  # read everything except other profiles' transcripts
#   ./scripts/register-mcp.sh --scope         # strict: own corpus, skills, notes only
#   ./scripts/register-mcp.sh --allow a,b     # one explicit allowlist for every profile
#
# Every profile shares one store, so without a scope each agent can read every other
# profile's transcripts. --scope is the fix: the wrapper env carries RAG_ALLOWED_CORPORA.
#
# Idempotent: re-running rewrites the wrapper and re-asserts the same values.
set -uo pipefail

unset PYTHONPATH PYTHONHOME PYTHONUSERBASE
export PYTHONNOUSERSITE=1

cd "$(dirname "$0")/.." || exit 1
ROOT=$(pwd)
HERMES_HOME_DIR="${RAG_HERMES_HOME:-$HOME/.hermes}"
WRAPPER="${RAG_WRAPPER:-$ROOT/bin/rag-mcp}"
PROFILES_DIR="$HERMES_HOME_DIR/profiles"

say() { printf '\n== %s\n' "$1"; }
die() { echo "error: $*" >&2; exit 1; }

say "preflight"
HERMES_BIN="${HERMES_BIN:-$(command -v hermes || true)}"
if [ -z "$HERMES_BIN" ] && [ -x "$HOME/.local/bin/hermes" ]; then
    HERMES_BIN="$HOME/.local/bin/hermes"
fi
[ -n "$HERMES_BIN" ] || die "hermes not found — put it on PATH or set HERMES_BIN"
[ -f "$ROOT/wetnoodle/mcp_server.py" ] || die "wetnoodle/mcp_server.py not found in $ROOT — run this from the repo"
# RAG_PYTHON lets an orchestrating distribution point at a venv it manages
# elsewhere (bootstrap.sh uses the same knob to choose the base interpreter).
# Default stays this checkout's own .venv.
PY_BIN="${RAG_PYTHON:-$ROOT/.venv/bin/python}"
[ -x "$PY_BIN" ] || die "no interpreter at $PY_BIN — run ./scripts/bootstrap.sh, or set RAG_PYTHON"
echo "  repo      : $ROOT"
echo "  python    : $PY_BIN"
echo "  hermes    : $HERMES_BIN"

SCOPE=""
SHARED=""
ALLOW="${RAG_ALLOWED_CORPORA:-}"
while [ "$#" -gt 0 ]; do
    case "$1" in
        --scope) SCOPE=1; shift ;;
        --scope-shared) SHARED=1; shift ;;
        --allow) ALLOW="${2:-}"; shift 2 ;;
        --allow=*) ALLOW="${1#*=}"; shift ;;
        *) break ;;
    esac
done

say "wrapper"
mkdir -p "$(dirname "$WRAPPER")"
cat >"$WRAPPER" <<WRAP
#!/bin/sh
# generated by wetnoodle scripts/register-mcp.sh — re-run it rather than editing this
exec env -u PYTHONPATH -u PYTHONHOME -u PYTHONUSERBASE -u PYTHONSTARTUP \
    PYTHONPATH="$ROOT" "$PY_BIN" -m wetnoodle.mcp_server "\$@"
WRAP
chmod +x "$WRAPPER"
echo "  $WRAPPER"

say "targets"
if [ "$#" -gt 0 ]; then
    TARGETS="$*"
else
    # Portable: `find -printf` is GNU-only, so on macOS this listed nothing and the script
    # reported that no profiles existed.
    TARGETS=$(for d in "$PROFILES_DIR"/*/; do [ -d "$d" ] && basename "$d"; done | sort)
    [ -n "$TARGETS" ] || die "no profiles found under $PROFILES_DIR — pass profile names explicitly"
fi
echo "  $(echo "$TARGETS" | tr '\n' ' ')"

say "registering"
for p in $TARGETS; do
    note=""          # set -u: referenced below whether or not RAG_DIR was given
    if ! "$HERMES_BIN" -p "$p" config set mcp_servers.wetnoodle.command "$WRAPPER" >/dev/null 2>&1; then
        echo "  $p: FAILED (does this profile exist? try: hermes gateway list)"
        continue
    fi
    "$HERMES_BIN" -p "$p" config set mcp_servers.wetnoodle.enabled true >/dev/null 2>&1
    if [ -n "${RAG_DIR:-}" ]; then
        "$HERMES_BIN" -p "$p" config set mcp_servers.wetnoodle.env.RAG_DIR "$RAG_DIR" >/dev/null 2>&1
        note="store=$RAG_DIR"
    fi
    scope_value="$ALLOW"
    exclude_value=""
    if [ -n "$SHARED" ] && [ -z "$scope_value" ]; then
        # Corpora are named after the profile that owns them, so excluding the other profile
        # names hides their transcripts while every shared corpus — skills, imported manuals,
        # notes — stays reachable.
        # every profile on the machine, not only the ones named on this command line:
        # `default` owns a corpus too, and passing two names would leave it readable
        # Named profiles only. `default` is the base install: hiding it by default would cut
        # every profile off from the longest-running history on the machine. Use --scope (or
        # add it to the exclusion yourself) when that is what you want.
        peers=$(for d in "$PROFILES_DIR"/*/; do [ -d "$d" ] && basename "$d"; done)
        for other in $peers; do
            [ "$other" = "$p" ] && continue
            exclude_value="$exclude_value,$other"
        done
        exclude_value="${exclude_value#,}"
        # clear any allowlist left by an earlier --scope run, or the two rules combine into
        # the stricter of the two and every newly ingested shared corpus stays invisible
        "$HERMES_BIN" -p "$p" config set mcp_servers.wetnoodle.env.RAG_ALLOWED_CORPORA "" >/dev/null 2>&1
        if [ -n "$exclude_value" ]; then
            "$HERMES_BIN" -p "$p" config set mcp_servers.wetnoodle.env.RAG_EXCLUDED_CORPORA \
                "$exclude_value" >/dev/null 2>&1 || echo "  $p: warning — could not set exclusion"
            note="$note reading everything except: $exclude_value"
        fi
    fi
    if [ -z "$scope_value" ] && [ -n "$SCOPE" ]; then
        scope_value="$p,skill,notes"
    fi
    if [ -n "$scope_value" ]; then
        "$HERMES_BIN" -p "$p" config set mcp_servers.wetnoodle.env.RAG_ALLOWED_CORPORA \
            "$scope_value" >/dev/null 2>&1 || echo "  $p: warning — could not set scope"
        note="$note scope=$scope_value"
    fi
    # `note` already carries the store when RAG_DIR was exported; the old `else` replaced it
    # with the word "default", which read as if the wrong store had been configured.
    printf '  %-16s registered (%s)\n' "$p" "${note:-defaults}"
done

cat <<'DONE'

Next: restart the gateway, or start a new session. The tools appear as
`mcp__wetnoodle__rag_search`, `rag_open`, `rag_audit`.

Verify from the shell at any time:
  ./.venv/bin/python -m wetnoodle.doctor
  ./.venv/bin/python -m wetnoodle.ingest --status
DONE
